/**
 * Harvest the lux layer id -> template filename mapping.
 *
 * The mapping lives only in the backend table `lux_getfeature_definition` and is
 * not exposed by the themes API, but the aggregated `/getfeatureinfo` response
 * names the template of every layer it answers for. So: walk a grid of points
 * over Luxembourg, ask the aggregated endpoint about the queryable layers we
 * have not mapped yet, and record what it reports.
 *
 * This only ever sees layers that have data at one of the probed points, so the
 * result is a seed, not the truth. The authoritative list is
 * `SELECT layer, template FROM lux_getfeature_definition` — replace this seed
 * with that the day someone with admin-DB access can run it.
 *
 * Usage: node scripts/harvest-templates.mjs [> src/luxTemplates.ts]
 */
import process from 'node:process';

const THEMES_URL =
  'https://map.geoportail.lu/themes?limit=30&partitionlimit=5&interface=main&background=background';
const INFO_URL = 'https://map.geoportail.lu/getfeatureinfo';

/** EPSG:2169 points spread over the country: cities, towns, valleys, borders. */
const POINTS = [
  [77244, 75040], // Luxembourg City
  [63500, 62000], // Esch-sur-Alzette
  [74000, 100000], // Ettelbruck
  [78500, 101500], // Diekirch
  [96000, 84000], // Grevenmacher
  [64500, 110000], // Wiltz
  [99000, 96000], // Echternach
  [93000, 68000], // Remich
  [68500, 122000], // Clervaux
  [74000, 88000], // Mersch
];

const BOX = 100; // metres; wide on purpose, we only want the template name
const CHUNK = 25;

async function queryableLayerIds() {
  const themes = await (await fetch(THEMES_URL)).json();
  const ids = [];
  const seen = new Set();
  (function walk(node) {
    if (node.metadata?.is_queryable && !seen.has(String(node.id))) {
      seen.add(String(node.id));
      ids.push(String(node.id));
    }
    (node.children ?? []).forEach(walk);
  })({ children: themes.themes });
  return ids;
}

async function probe(point, layerIds) {
  const [x, y] = point;
  const box = [x - BOX, y + BOX, x + BOX, y - BOX].join(',');
  const params = new URLSearchParams({
    layers: layerIds.join(','),
    box1: box,
    box2: box,
    srs: 'EPSG:3857',
    zoom: '17',
    BBOX: '0,0,1,1',
    WIDTH: '101',
    HEIGHT: '101',
    X: '50',
    Y: '50',
  });
  try {
    const res = await fetch(`${INFO_URL}?${params}`);
    if (!res.ok) {
      return [];
    }
    const json = await res.json();
    return Array.isArray(json) ? json : [];
  } catch {
    return [];
  }
}

const ids = await queryableLayerIds();
const mapping = new Map();
process.stderr.write(`${ids.length} queryable layers to map\n`);

for (const point of POINTS) {
  const todo = ids.filter((id) => !mapping.has(id));
  if (todo.length === 0) {
    break;
  }
  for (let i = 0; i < todo.length; i += CHUNK) {
    // eslint-disable-next-line no-await-in-loop
    const entries = await probe(point, todo.slice(i, i + CHUNK));
    entries.forEach((entry) => {
      // Some layers answer with a remote-template URL
      // (`getpoitemplate?layer=…`, i.e. `remote_template: true`); the templates
      // package cannot render those, so leave them to the default template.
      if (
        typeof entry.template === 'string' &&
        entry.template.endsWith('.html') &&
        !mapping.has(String(entry.layer))
      ) {
        mapping.set(String(entry.layer), entry.template);
      }
    });
  }
  process.stderr.write(`  ${point.join(',')} -> mapped ${mapping.size}\n`);
}

const sorted = [...mapping.entries()].sort(
  (a, b) => Number(a[0]) - Number(b[0]),
);
const counts = sorted.reduce((acc, [, tpl]) => {
  acc[tpl] = (acc[tpl] ?? 0) + 1;
  return acc;
}, {});
process.stderr.write(
  `\nmapped ${sorted.length}/${ids.length}; distinct templates: ${Object.keys(counts).length}\n`,
);
Object.entries(counts)
  .sort((a, b) => b[1] - a[1])
  .forEach(([tpl, n]) =>
    process.stderr.write(`  ${String(n).padStart(4)} ${tpl}\n`),
  );

process.stdout
  .write(`/* eslint-disable @typescript-eslint/naming-convention -- keys are numeric lux layer ids */
/**
 * Lux layer id -> GetFeatureInfo template filename.
 *
 * GENERATED by \`node scripts/harvest-templates.mjs\` — do not edit by hand.
 *
 * The mapping exists only in the backend table \`lux_getfeature_definition\`;
 * neither the themes API nor a standard WMS GetFeatureInfo response carries it.
 * A layer missing from this map renders with \`default.html\`, which is also how
 * the backend signals "render generically", so an incomplete map degrades
 * gracefully rather than breaking.
 *
 * Harvested from ${POINTS.length} points, covering ${sorted.length} of ${ids.length}
 * queryable layers — only layers with data at a probed point can be seen. Replace
 * with \`SELECT layer, template FROM lux_getfeature_definition\` when possible.
 */
const luxTemplates: Record<string, string> = {
${sorted.map(([id, tpl]) => `  '${id}': '${tpl}',`).join('\n')}
};

export default luxTemplates;
`);
